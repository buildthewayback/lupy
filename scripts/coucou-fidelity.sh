#!/usr/bin/env bash
# Coucou fidelity report: compares Lupy's Mac/ with the Coucou commit it was imported from.
#   scripts/coucou-fidelity.sh <path-to-coucou-checkout> > docs/COUCOU_FIDELITY.md
# Lists every upstream file kept byte-identical, every file Lupy changed (with the size of the
# change), and the files Lupy added. The Mochi character, its animations, the island, the window
# and Settings are Coucou's own code: identical files are the evidence.
set -euo pipefail
SRC="${1:?usage: coucou-fidelity.sh <coucou checkout>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REV=$(awk 'NR==1 {print $2}' "$ROOT/Mac/UPSTREAM.txt")
git -C "$SRC" cat-file -e "$REV^{commit}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
git -C "$SRC" archive "$REV" NotchBuddy/Sources/App NotchBuddy/Sources/CoucouKit NotchBuddy/Assets.xcassets NotchBuddy/Resources/sounds NotchBuddy/Resources/Localizable.xcstrings | tar -x -C "$TMP"
UP="$TMP/NotchBuddy"

map() { # upstream relative path -> Lupy path
  case "$1" in
    Sources/*) echo "Mac/$1" ;;
    Assets.xcassets/*) echo "Mac/CoucouAssets/$1" ;;
    Resources/sounds/*) echo "Mac/CoucouAssets/sounds/${1#Resources/sounds/}" ;;
    Resources/Localizable.xcstrings) echo "Mac/Resources/Localizable.xcstrings" ;;
  esac
}

same=0; changed=0; missing=0
changed_rows=""; missing_rows=""
while IFS= read -r f; do
  rel="${f#"$UP"/}"
  ours="$ROOT/$(map "$rel")"
  if [ ! -f "$ours" ]; then missing=$((missing + 1)); missing_rows="$missing_rows| \`$rel\` |\n"; continue; fi
  if cmp -s "$f" "$ours"; then same=$((same + 1)); else
    changed=$((changed + 1))
    stat=$(diff -U0 "$f" "$ours" | grep -cE '^[+-][^+-]' || true)
    changed_rows="$changed_rows| \`$(map "$rel")\` | $stat |\n"
  fi
done < <(find "$UP" -type f ! -name '.DS_Store' | sort)

added=$(cd "$ROOT" && find Mac/Sources/Lupy -name '*.swift' | sort)
added_lines=$(cd "$ROOT" && cat $added | wc -l | tr -d ' ')
mochi="Sources/CoucouKit/BotEngine.swift Sources/CoucouKit/MochiOutfitDrawing.swift Sources/CoucouKit/MochiMood.swift Sources/CoucouKit/MochiStill.swift Sources/CoucouKit/MochiWardrobe.swift Sources/App/BotCanvasView.swift Sources/App/DesktopMochi.swift Sources/App/GreetingCanvasView.swift Sources/App/IslandRootView.swift Sources/App/IslandWindowController.swift Sources/App/IslandStateMachine.swift Sources/CoucouKit/IslandScreenGeometry.swift"

echo "# Coucou fidelity report"
echo
echo "Generated by \`scripts/coucou-fidelity.sh\` on $(date -u +%Y-%m-%d) — Lupy \`$(git -C "$ROOT" rev-parse --short HEAD)\` against Coucou \`${REV:0:7}\` (Louis-CFM/coucou)."
echo
echo "## Summary"
echo
echo "| | Files |"
echo "|---|---|"
echo "| Coucou files kept **byte-identical** (code, artwork, sounds) | $same |"
echo "| Coucou files Lupy changed (small hooks; see below) | $changed |"
echo "| Coucou files not imported | $missing |"
echo "| Files Lupy added (\`Mac/Sources/Lupy\`) | $(echo "$added" | wc -l | tr -d ' ') files, $added_lines lines |"
echo
echo "## Mochi, its animations and the island — identical to Coucou?"
echo
echo "| File | Status |"
echo "|---|---|"
for m in $mochi; do
  if cmp -s "$UP/$m" "$ROOT/Mac/$m"; then echo "| \`$m\` | identical |"; else echo "| \`$m\` | changed ($(diff -U0 "$UP/$m" "$ROOT/Mac/$m" | grep -cE '^[+-][^+-]' || true) lines) |"; fi
done
echo
echo "## Coucou files Lupy changed"
echo
echo "Every change is marked \`Lupy:\` in the file. Lines = added + removed lines in the diff."
echo
echo "| File | Changed lines |"
echo "|---|---|"
printf "%b" "$changed_rows"
if [ "$missing" -gt 0 ]; then
  echo
  echo "## Not imported"
  echo
  printf "%b" "$missing_rows"
fi
echo
echo "## Added by Lupy"
echo
echo "$added" | sed 's/^/- `/; s/$/`/'
